#!/usr/bin/env node
// Builds the SQL that loads the serviceable / excluded ("grey vs white") layer
// of a Lane instructor-zones KMZ into `service_area_zones`.
//
//   node scripts/generate-service-area-zones-migration.mjs "<file>.kmz" <out.sql>
//
// How the KMZ encodes it: the "Non-demand blackout" folder holds one huge black
// rectangle with HOLES (the holes are the white = serviceable areas) plus small
// black polygons inside those holes (pockets we do not serve). So:
//   - each hole of the mask        -> a `serviceable` row
//   - each small black polygon     -> an `excluded` row
// The rectangle itself is NOT stored; the map draws "everything else" as grey.
//
// Instructor placemarks are ignored: they live in `instructor_service_zones`.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const [kmz, out] = process.argv.slice(2);
if (!kmz || !out) {
  console.error('usage: node scripts/generate-service-area-zones-migration.mjs "<file>.kmz" <out.sql>');
  process.exit(1);
}

const dir = mkdtempSync(path.join(tmpdir(), "kmz-"));
let xml;
try {
  execFileSync("unzip", ["-o", "-q", kmz, "doc.kml", "-d", dir]);
  xml = readFileSync(path.join(dir, "doc.kml"), "utf8");
} finally {
  // read before cleanup
}
rmSync(dir, { recursive: true, force: true });

const folders = [...xml.matchAll(/<Folder>([\s\S]*?)<\/Folder>/g)].map((m) => m[1]);
const blackout = folders.find((f) => /<name>Non-demand blackout<\/name>/.test(f));
if (!blackout) throw new Error('No "Non-demand blackout" folder in this KMZ');

const ring = (s) =>
  s
    .trim()
    .split(/\s+/)
    .map((t) => t.split(",").map(Number))
    .filter((p) => p.length >= 2 && Number.isFinite(p[0]) && Number.isFinite(p[1]))
    .map(([lng, lat]) => ({ lat, lng }));

const placemarks = [...blackout.matchAll(/<Placemark[^>]*>([\s\S]*?)<\/Placemark>/g)].map((m) => m[1]);
const parsed = placemarks.map((b) => ({
  name: ((b.match(/<name>([\s\S]*?)<\/name>/) || [])[1] || "").split("<br>")[0].trim(),
  outer: [...b.matchAll(/<outerBoundaryIs>[\s\S]*?<coordinates>([\s\S]*?)<\/coordinates>/g)].map((x) => ring(x[1]))[0],
  holes: [...b.matchAll(/<innerBoundaryIs>[\s\S]*?<coordinates>([\s\S]*?)<\/coordinates>/g)].map((x) => ring(x[1])),
}));

const masks = parsed.filter((p) => p.holes.length > 0);
if (masks.length !== 1) throw new Error(`Expected exactly one mask polygon with holes, found ${masks.length}`);
const mask = masks[0];
const pockets = parsed.filter((p) => p.holes.length === 0);

const centre = (r) => ({
  lat: r.reduce((a, p) => a + p.lat, 0) / r.length,
  lng: r.reduce((a, p) => a + p.lng, 0) / r.length,
});
const area = (r) => {
  // km2, flat projection around Bengaluru; only used to rank/name the holes
  let s = 0;
  const kx = 111.32 * Math.cos((12.95 * Math.PI) / 180);
  for (let i = 0; i < r.length - 1; i++)
    s += r[i].lng * kx * r[i + 1].lat * 110.57 - r[i + 1].lng * kx * r[i].lat * 110.57;
  return Math.abs(s) / 2;
};

// Stable, human names: biggest = main Bengaluru area, Mysuru by latitude, the
// rest numbered west->east.
const holes = mask.holes.map((r) => ({ ring: r, c: centre(r), a: area(r) }));
const biggest = holes.reduce((a, b) => (b.a > a.a ? b : a));
const mysuru = holes.filter((h) => h !== biggest && h.c.lat > 12.25 && h.c.lat < 12.4 && h.c.lng < 77);
const others = holes
  .filter((h) => h !== biggest && !mysuru.includes(h))
  .sort((a, b) => a.c.lng - b.c.lng);
const serviceable = [
  { name: "Serviceable area - Bengaluru", ring: biggest.ring },
  ...mysuru.map((h, i) => ({
    name: `Serviceable area - Mysuru${mysuru.length > 1 ? ` ${i + 1}` : ""}`,
    ring: h.ring,
  })),
  ...others.map((h, i) => ({ name: `Serviceable area - Bengaluru south ${i + 1}`, ring: h.ring })),
];

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const row = (kind, name, r, notes) =>
  `  (${q(kind)}, ${q(name)}, ${q(JSON.stringify(r))}::jsonb, ${q("Lane instructor driving zones.kmz")}, ${q(notes)})`;

const rows = [
  ...serviceable.map((z) =>
    row("serviceable", z.name, z.ring, "White area: a cut-out of the KMZ's Non-demand blackout mask."),
  ),
  ...pockets.map((p) =>
    row("excluded", p.name, p.outer, "Black pocket inside a serviceable area: not served."),
  ),
];

const sql = `-- Serviceable (white) vs non-serviceable (grey) layer for the Instructor Zone Map.
-- Generated by scripts/generate-service-area-zones-migration.mjs from
-- "Lane instructor driving zones.kmz" (folder "Non-demand blackout").
--
-- Model: store the WHITE areas and the small excluded pockets inside them. The
-- giant black rectangle of the KMZ is NOT stored -- grey is simply "everywhere
-- that is not serviceable" and is drawn by the map. Instructor polygons are NOT
-- part of this table; they stay in instructor_service_zones.
--   kind = 'serviceable' : an area where Lane offers service (white)
--   kind = 'excluded'    : a pocket inside a serviceable area that is not served
-- A point is serviceable when it is inside a 'serviceable' ring and inside no
-- 'excluded' ring.
--
-- Reads/writes need public.is_admin_or_team_member() (same helper and policies
-- as instructor_service_zones). Re-running is safe (upsert on kind + name).

DO $$
BEGIN
  IF to_regprocedure('public.is_admin_or_team_member()') IS NULL THEN
    RAISE EXCEPTION 'Required helper public.is_admin_or_team_member() is missing.';
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.service_area_zones (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kind text NOT NULL CHECK (kind IN ('serviceable', 'excluded')),
  name text NOT NULL,
  -- [{lat, lng}, ...] closed ring (first point repeated last, KML convention)
  coordinates jsonb NOT NULL,
  source text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT service_area_zones_coordinates_valid CHECK (
    jsonb_typeof(coordinates) = 'array' AND jsonb_array_length(coordinates) >= 3
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_service_area_zones_kind_name
  ON public.service_area_zones (kind, name);

DROP TRIGGER IF EXISTS trg_service_area_zones_updated_at ON public.service_area_zones;
CREATE TRIGGER trg_service_area_zones_updated_at
  BEFORE UPDATE ON public.service_area_zones
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_updated_at();

ALTER TABLE public.service_area_zones ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.service_area_zones FROM anon;
GRANT ALL ON public.service_area_zones TO authenticated;
GRANT ALL ON public.service_area_zones TO service_role;

DROP POLICY IF EXISTS "Admins and team members can view service area zones" ON public.service_area_zones;
CREATE POLICY "Admins and team members can view service area zones"
  ON public.service_area_zones FOR SELECT USING (public.is_admin_or_team_member());

DROP POLICY IF EXISTS "Admins and team members can create service area zones" ON public.service_area_zones;
CREATE POLICY "Admins and team members can create service area zones"
  ON public.service_area_zones FOR INSERT WITH CHECK (public.is_admin_or_team_member());

DROP POLICY IF EXISTS "Admins and team members can update service area zones" ON public.service_area_zones;
CREATE POLICY "Admins and team members can update service area zones"
  ON public.service_area_zones FOR UPDATE
  USING (public.is_admin_or_team_member()) WITH CHECK (public.is_admin_or_team_member());

DROP POLICY IF EXISTS "Admins and team members can delete service area zones" ON public.service_area_zones;
CREATE POLICY "Admins and team members can delete service area zones"
  ON public.service_area_zones FOR DELETE USING (public.is_admin_or_team_member());

INSERT INTO public.service_area_zones (kind, name, coordinates, source, notes) VALUES
${rows.join(",\n")}
ON CONFLICT (kind, name) DO UPDATE
  SET coordinates = EXCLUDED.coordinates,
      source = EXCLUDED.source,
      notes = EXCLUDED.notes;
`;

writeFileSync(out, sql);
console.log(
  `wrote ${out}: ${serviceable.length} serviceable + ${pockets.length} excluded rows`,
);
for (const z of serviceable) console.log(`  serviceable  ${z.name}  (${z.ring.length} pts)`);
for (const p of pockets) console.log(`  excluded     ${p.name}  (${p.outer.length} pts)`);
