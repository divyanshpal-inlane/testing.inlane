// Run with Node from the project root. Refresh the seed when lesson content changes.
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { build } = createRequire(require.resolve("vite"))("esbuild");
import { writeFile, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
const temp = await mkdtemp(join(tmpdir(), "learning-catalog-"));
try {
  await build({
    stdin: {
      contents:
        'export {COURSES_DATA} from "./src/constants/courses"; export {videoId,quizId,questionId} from "./src/lib/learning-analytics/model";',
      resolveDir: process.cwd(),
    },
    bundle: true,
    platform: "node",
    format: "esm",
    outfile: join(temp, "catalog.mjs"),
    alias: { "@": resolve("src") },
    jsx: "automatic",
  });
  const { COURSES_DATA, videoId, quizId, questionId } = await import(
    pathToFileURL(join(temp, "catalog.mjs"))
  );
  const rows = [];
  for (const course of Object.values(COURSES_DATA))
    for (const [number, lesson] of Object.entries(course.lessonsData)) {
      for (const video of lesson.menu?.video ?? [])
        rows.push({
          course_id: course.id,
          lesson_number: Number(number),
          content_id: videoId(video.video_path),
          course_title: course.label,
          title: video.title,
          kind: "video",
          questions: [],
        });
      const game = lesson.content.game;
      if (lesson.menu?.trivia && game?.games.length) {
        const questions = game.games.map((q) => ({
          id: questionId(q.question),
          question: q.question,
          answers:
            game.type === "question"
              ? q.answers
              : q.mapAreas.map((a) => String(a.id)),
          correct:
            game.type === "question"
              ? q.answers[q.correctAnswer - 1]
              : String(q.correctAnswer),
        }));
        if (new Set(questions.map((q) => q.id)).size !== questions.length)
          throw Error(`Duplicate question in ${course.label} ${number}`);
        rows.push({
          course_id: course.id,
          lesson_number: Number(number),
          content_id: quizId(game),
          course_title: course.label,
          title: lesson.menu.trivia.title,
          kind: "quiz",
          questions,
        });
      }
    }
  const quote = (v) => "'" + String(v).replaceAll("'", "''") + "'";
  const sql =
    "-- Generated by scripts/generate-learning-catalog.mjs. Keep content IDs/versioned question banks intact.\nUPDATE public.learning_content SET active=false;\nINSERT INTO public.learning_content(course_id,lesson_number,content_id,course_title,title,kind,questions) VALUES\n" +
    rows
      .map(
        (r) =>
          "(" +
          [
            quote(r.course_id),
            r.lesson_number,
            quote(r.content_id),
            quote(r.course_title),
            quote(r.title),
            quote(r.kind),
            quote(JSON.stringify(r.questions)) + "::jsonb",
          ].join(",") +
          ")",
      )
      .join(",\n") +
    "\nON CONFLICT(course_id,lesson_number,content_id) DO UPDATE SET title=EXCLUDED.title,course_title=EXCLUDED.course_title,active=true;\n";
  await writeFile(
    process.argv[2] ||
      "supabase/migrations/20260911050100_learning_content_catalog.sql",
    sql,
  );
  console.log(`Generated ${rows.length} learning content entries.`);
} finally {
  await rm(temp, { recursive: true, force: true });
}
